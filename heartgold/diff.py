"""Differential testing across candidates (DiffSpec-style): run every candidate on many probe
expressions, collect disagreements, let a spec-reading judge decide the right answers, and turn
the verdicts into exact-value tests."""
import json, pathlib, subprocess, sys

# eval is intentional: probe expressions call the target repo's own code inside a throwaway
# worktree, which is the same trust level as running that repo's test suite.
RUNNER = r'''
import json, signal, sys
sys.path.insert(0, ".")
probe = json.load(open(sys.argv[1]))
ns = {}
exec(probe["setup"], ns)
def _alarm(*a):
    raise TimeoutError("probe timeout")
signal.signal(signal.SIGALRM, _alarm)
out = []
for expr in probe["exprs"]:
    signal.alarm(2)
    try:
        r = eval(expr, ns)
        out.append("=" + repr(r))
    except TimeoutError:
        out.append("!timeout")
    except Exception as e:
        out.append("!" + type(e).__name__)
    finally:
        signal.alarm(0)
print(json.dumps(out))
'''


def run_probe(wt, probe_path):
    runner = pathlib.Path(wt).resolve() / ".heartgold_probe_runner.py"
    runner.write_text(RUNNER)
    try:
        p = subprocess.run([sys.executable, str(runner), str(pathlib.Path(probe_path).resolve())], cwd=runner.parent, capture_output=True,
                           text=True, timeout=900)
        return json.loads(p.stdout.strip().splitlines()[-1])
    except Exception:
        return None
    finally:
        runner.unlink(missing_ok=True)


def disagreements(cands, probe_path, cap=40):
    """cands: list of worktree paths. Returns list of {expr, outputs{i: out}}."""
    probe = json.loads(pathlib.Path(probe_path).read_text())
    results = [run_probe(wt, probe_path) for wt in cands]
    rows = []
    for k, expr in enumerate(probe["exprs"]):
        outs = {i: r[k] for i, r in enumerate(results) if r and k < len(r)}
        if len(set(outs.values())) > 1:
            rows.append(dict(expr=expr, outputs=outs))
    # prefer variety: one per distinct output-pattern first
    seen, picked, rest = set(), [], []
    for r in rows:
        sig = tuple(sorted(set(r["outputs"].values())))
        (rest if sig in seen else picked).append(r)
        seen.add(sig)
    return (picked + rest)[:cap], len(rows), len(probe["exprs"])


def tests_from_verdicts(setup, verdicts):
    """verdicts: [{expr, expected: '=<repr>' | '!ExcName' | 'unsure'}] -> pytest source."""
    lines = ["# Generated by heartgold differential testing: candidates disagreed here and a judge",
             "# decided the correct behaviour from the specification.", "import pytest", setup, "", ""]
    n = 0
    for v in verdicts:
        exp, expr = v.get("expected", ""), v.get("expr", "")
        if not expr or not exp or exp == "unsure":
            continue
        n += 1
        why = (v.get("why") or "").replace("\n", " ")[:200]
        if exp.startswith("="):
            lines += [f"def test_diff_{n}():", f"    # {why}", f"    assert ({expr}) == {exp[1:]}", "", ""]
        elif exp.startswith("!"):
            exc = exp[1:]
            if not exc.isidentifier():
                continue
            lines += [f"def test_diff_{n}():", f"    # {why}",
                      f"    with pytest.raises(globals().get({exc!r}) or getattr(__import__('builtins'), {exc!r}, Exception)):",
                      f"        {expr}", "", ""]
    return "\n".join(lines), n
